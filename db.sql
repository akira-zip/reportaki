CREATE DATABASE REPORTAKI;

USE REPORTAKI;

CREATE TABLE USUARIO (
    ID INT UNSIGNED AUTO_INCREMENT,
    EMAIL VARCHAR(255) NOT NULL,
    SENHA VARCHAR(255) NOT NULL,
    DATA_CADASTRO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_USUARIO_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE CIDADAO (
    ID INT UNSIGNED AUTO_INCREMENT,
    ID_USUARIO INT UNSIGNED NOT NULL,
    CPF CHAR(11) NOT NULL,
    PSEUDONIMO VARCHAR(50) NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_CIDADAO_CPF UNIQUE (CPF),
    CONSTRAINT FK_CIDADAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID)
);

CREATE TABLE PREFEITURA (
    ID INT UNSIGNED AUTO_INCREMENT,
    ID_USUARIO INT UNSIGNED NOT NULL,
    CNPJ CHAR(14) NOT NULL,
    MUNICIPIO VARCHAR(100) NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_PREFEITURA_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UNIQUE_PREFEITURA_CNPJ UNIQUE (CNPJ),
    CONSTRAINT FK_PREFEITURA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID)
);

CREATE TABLE CATEGORIA (
    ID INT UNSIGNED AUTO_INCREMENT,
    NOME VARCHAR(50) NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_CATEGORIA_NOME UNIQUE (NOME)
);

CREATE TABLE DENUNCIA (
    ID INT UNSIGNED AUTO_INCREMENT,
    PROTOCOLO VARCHAR(20) NOT NULL,
    DESCRICAO TEXT NOT NULL,
    ENDERECO VARCHAR(255) NOT NULL,
    STATUS ENUM('NAO_INICIADO', 'INICIADO', 'FINALIZADO') NOT NULL DEFAULT 'NAO_INICIADO',
    DATA_ENVIO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    ID_CIDADAO INT UNSIGNED NOT NULL,
    ID_PREFEITURA INT UNSIGNED NOT NULL,
    ID_CATEGORIA INT UNSIGNED NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_DENUNCIA_PROTOCOLO UNIQUE (PROTOCOLO),
    CONSTRAINT FK_DENUNCIA_CIDADAO FOREIGN KEY (ID_CIDADAO) REFERENCES CIDADAO (ID),
    CONSTRAINT FK_DENUNCIA_PREFEITURA FOREIGN KEY (ID_PREFEITURA) REFERENCES PREFEITURA (ID),
    CONSTRAINT FK_DENUNCIA_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID),
    INDEX INDEX_DENUNCIA_CIDADAO (ID_CIDADAO),
    INDEX INDEX_DENUNCIA_PREFEITURA (ID_PREFEITURA),
    INDEX INDEX_DENUNCIA_CATEGORIA (ID_CATEGORIA)
);

CREATE TABLE MIDIA (
    ID INT UNSIGNED AUTO_INCREMENT,
    ID_DENUNCIA INT UNSIGNED NOT NULL,
    URL_ARQUIVO VARCHAR(255) NOT NULL,
    PRIMARY KEY (ID),
    CONSTRAINT FK_MIDIA_DENUNCIA FOREIGN KEY (ID_DENUNCIA) REFERENCES DENUNCIA (ID),
    INDEX INDEX_MIDIA_DENUNCIA (ID_DENUNCIA)
);