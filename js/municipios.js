// Preenche a lista de sugestões (datalist) dos campos de município
function preencherListaMunicipios() {
    const lista = document.getElementById("lista-municipios")
    
    if (!lista) {
        return
    }

    const opcoes = MUNICIPIOS.map((nome) => {
        const opcao = document.createElement("option")
        opcao.value = nome
        return opcao
    })
    lista.replaceChildren(...opcoes)
}

if (document.readyState == "loading") {
    document.addEventListener("DOMContentLoaded", preencherListaMunicipios)
}
else {
    preencherListaMunicipios()
}